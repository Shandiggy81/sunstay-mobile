#!/usr/bin/env node
/**
 * Stage City of Melbourne CLUE outdoor-seating venues as SunStay import
 * candidates. Writes SQL that fills public.venue_import_candidates; it never
 * touches public.venues. Promotion is a separate, reviewed step.
 *
 *   node scripts/importClueVenues.mjs --existing existing.json [--input clue.json] [--year 2024] [--out stage.sql]
 *
 *   --existing  JSON array of current venues [{ id, name|venueName, lat, lng }], e.g. from
 *               select json_agg(json_build_object('id',id,'name',"venueName",'lat',lat,'lng',lng)) from public.venues;
 *   --input     a saved CLUE export; without it the script downloads the year's
 *               outdoor-seating records from data.melbourne.vic.gov.au
 *
 * Needs supabase/proposed/venue_import_candidates.sql applied first (approval required).
 * Then, as the service role:
 *   \i stage.sql
 *   select public.place_venue_candidate(id) from public.venue_import_candidates where status = 'new';
 *
 * Data © City of Melbourne (CLUE), CC BY 4.0.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { CLUE_ATTRIBUTION, clueCandidateId, dedupeClueRows, duplicateIds, isLaneway, matchExisting, streetAxes } from '../src/utils/clueImport.js';

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => {
    if (a.startsWith('--')) acc.push([a.slice(2), all[i + 1] && !all[i + 1].startsWith('--') ? all[i + 1] : true]);
    return acc;
}, []));
const year = Number(args.year) || 2024;
if (!args.existing) {
    console.error('Usage: node scripts/importClueVenues.mjs --existing existing.json [--input clue.json] [--year 2024] [--out stage.sql]');
    process.exit(1);
}

const DATASET = 'https://data.melbourne.vic.gov.au/api/explore/v2.1/catalog/datasets/cafes-and-restaurants-with-seating-capacity/exports/json';
let rows;
if (args.input) {
    rows = JSON.parse(readFileSync(args.input, 'utf8'));
} else {
    const where = encodeURIComponent(`year(census_year)=${year} and seating_type like "Outdoor%"`);
    const res = await fetch(`${DATASET}?where=${where}`);
    if (!res.ok) throw new Error(`CLUE download failed: ${res.status}`);
    rows = await res.json();
}
rows = rows.filter((r) => Number(r.census_year) === year && /^Seats - Outdoor/i.test(r.seating_type ?? ''));

const existing = JSON.parse(readFileSync(args.existing, 'utf8'));
const { candidates, skipped } = dedupeClueRows(rows);
const axes = streetAxes(candidates);
const clashes = duplicateIds(candidates.map(clueCandidateId));
if (clashes.length) throw new Error(`Candidate id clash: ${clashes.join(', ')}`);

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (Number.isFinite(v) ? String(v) : 'null');
const lines = [];
const report = { year, records: rows.length, candidates: candidates.length, skipped, duplicates: [], laneways: 0, no_street_axis: 0, upper_floor: 0, rooftop: 0 };

candidates.forEach((c) => {
    const dup = matchExisting(c, existing);
    if (dup) report.duplicates.push({ name: c.name, existing_id: dup.id, metres: dup.metres });
    const axis = c.street ? axes.get(c.street.toLowerCase()) : null;
    if (!axis) report.no_street_axis++;
    const lane = isLaneway(c.street);
    if (lane) report.laneways++;
    if (c.floor > 0) report.upper_floor++;
    if (c.rooftop) report.rooftop++;
    const id = clueCandidateId(c);
    lines.push(`(${[q(id), q(c.name), q(c.address), q(c.kind), q(c.area), q(c.property_id), num(c.census_year), num(c.lat), num(c.lng),
        num(c.outdoor_seats), q(c.street), num(axis?.bearing), num(axis?.lat), num(axis?.lng), lane, num(c.floor), c.rooftop,
        q(dup?.id ?? null), q(dup ? 'duplicate' : 'new')].join(', ')})`);
});

const sql = `-- Generated by scripts/importClueVenues.mjs for CLUE ${year}. ${CLUE_ATTRIBUTION}.
-- Stages candidates only; public.venues is untouched.
begin;
delete from public.venue_import_candidates where source = 'clue' and census_year = ${year} and status in ('new', 'duplicate');
insert into public.venue_import_candidates
  (id, name, address, kind, area, property_id, census_year, clue_lat, clue_lng, outdoor_seats,
   street, street_bearing, street_lat, street_lng, on_laneway, floor_level, rooftop, existing_venue_id, status)
select v.* from (values
${lines.join(',\n')}
) as v(id, name, address, kind, area, property_id, census_year, clue_lat, clue_lng, outdoor_seats,
       street, street_bearing, street_lat, street_lng, on_laneway, floor_level, rooftop, existing_venue_id, status)
-- Venues staged before 16 Oct 2026 have row-order ids (clue-2024-<property>-<n>),
-- so also match an already-staged venue by property and name: a re-run never
-- re-adds a venue that's placed or promoted.
where not exists (
  select 1 from public.venue_import_candidates c
  where c.source = 'clue' and c.property_id is not distinct from v.property_id
    and regexp_replace(lower(c.name), '[^a-z0-9]', '', 'g') = regexp_replace(lower(v.name), '[^a-z0-9]', '', 'g'))
on conflict (id) do nothing;
commit;
`;
if (args.out) writeFileSync(args.out, sql);
report.new = candidates.length - report.duplicates.length;
console.log(JSON.stringify(report, null, 1));
