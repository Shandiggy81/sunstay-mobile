#!/usr/bin/env node
/**
 * Regenerates supabase/seeds/20261014_stays.sql from src/data/demoVenues.js.
 *
 *   node scripts/buildStaysSeed.mjs
 *
 * Re-run after changing a stay in demoVenues.js (coordinates, rooms...), so the
 * seed never drifts from the app. Applying the seed to production needs
 * explicit approval (CLAUDE.md).
 */
import { writeFileSync } from 'node:fs';
import { demoVenues } from '../src/data/demoVenues.js';
import { venuePinUpdateSql, venueUpsertSql } from '../src/utils/venueSeed.js';

const OUT = new URL('../supabase/seeds/20261014_stays.sql', import.meta.url);
// The stays added in PR #129: inserted or fully updated.
const stays = demoVenues.filter(venue => venue.id.startsWith('dv-melb-stay-'));
// Hotels already in production whose pins were corrected on 14 Oct 2026
// (Google Maps place listings for the official addresses, each verified inside
// a building footprint). Only lat/lng change; nothing else on these rows.
const PIN_FIXES = ['dv-17', 'dv-hotel-01', 'dv-hotel-02', 'dv-hotel-03'];
const pinFixes = PIN_FIXES.map(id => {
    const venue = demoVenues.find(v => v.id === id);
    if (!venue) throw new Error(`${id} not found in demoVenues.js`);
    return venue;
});
if (!stays.length) throw new Error('No dv-melb-stay-* venues found in demoVenues.js');

const header = `-- Not applied. Apply only with explicit approval.
-- Generated by scripts/buildStaysSeed.mjs from src/data/demoVenues.js; do not edit by hand.
-- 1. Upserts ${stays.length} stays (Hotel / Serviced apartment) into public.venues: ${stays.map(v => v.id).join(', ')}.
--    Room types are illustrative facade estimates (source "estimated") pending venue verification.
-- 2. Moves the pins of ${pinFixes.length} existing hotels (lat/lng only): ${PIN_FIXES.join(', ')}.
`;
const body = [...stays.map(venueUpsertSql), ...pinFixes.map(venuePinUpdateSql)].join('\n\n');
writeFileSync(OUT, `${header}\nbegin;\n\n${body}\n\ncommit;\n`);
console.log(`Wrote ${stays.length} stays and ${pinFixes.length} pin fixes to supabase/seeds/20261014_stays.sql`);
